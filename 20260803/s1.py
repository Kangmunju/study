first, second = "A", "B"  # first = "A"   second = "B"
first, second = second, first  # 임시 변수 없이 한 줄로 교환 가능
print(first, second)  # B A
# 파이썬은 먼저 오른쪽 전체를 하나의 튜플로 만든다
# (second, first)라는 임시 객체를 생성 -> 그 다음 first, second 순서로 대입
# 기존 값이 사라지기 전에 이미 안전하게 보관되어 있기 때문에 오류가 나지 않음
