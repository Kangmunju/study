# 12. 심화 - 변수는 값을 담는 상자가 아닌 '값을 가리키는 화살표'
# --------------------------------------------------------
a = [1, 2, 3]  # 리스트를 만들고 a가 그것을 가리킴
b = a  # b는 a와 '같은' 리스트를 가리킨다, 복사가 아님에 주의!

b.append(4)  # b를 통해 리스트를 수정하면
print(a)  # [1, 2, 3, 4] <- a의 리스트 또한 변경되어 있음
# a와 b라는 두 이름이 동일한 리스트 객체 하나를 가리킴
# b 자체를 바꾼 것이 아니라, b가 참조하는 리스트 객체를 수정한 것

