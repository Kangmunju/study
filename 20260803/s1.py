# --------------------------------------------------------
# 1. 변수란?
# 변수 = 값에 붙이는 "이름표"
# 값을 메모리에 저장해 두고, 나중에 그 이름으로 다시 꺼내 쓰는 것
# --------------------------------------------------------

age = 25
# age -> 변수명(이름표)
# = -> 대입 연산자 : "오른쪽의 값을 왼쪽 이름에 넣어라"
# 25 -> 값(value) : 실제로 저장되는 데이터

print(age)  # 25 <- 이름을 부르면 값이 나옴

# 주의 : 수학의 '='이 아니라 '넣는다'는 뜻!
# 같은 지 비교할 때에는 '=='를 쓴다!


# --------------------------------------------------------
# 2. 변수는 언제든 값을 바꿀 수 있다. 그래서 '변'수
# --------------------------------------------------------

score = 90  # 처음에는 90
score = 100  # 나중에는 100으로 덮어씀
print(score)  # 100

# 자기 자신을 이용해서 바꾸기
count = 10  # 처음에 10을 넣었음
count = count + 5  # 오른쪽 먼저 계산(10+5 = 15) -> 결과를 다시 count에 넣음
print(count)  # 15

# 위와 똑같은 뜻인데 더 짧게 쓰는 방법(복합 대입 연산자)
count += 5  # count = count + 5 -> 20
count -= 3  # count = count - 3 -> 17
count *= 2  # count = count * 2 -> 34
count /= 2  # count = count / 2 -> 17.0 (나눗셈의 결과는 실수)
print(count)  # 17.0


