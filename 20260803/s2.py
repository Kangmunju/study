# --------------------------------------------------------
# 1. 자료형
# --------------------------------------------------------
# 변수 = 값에 붙이는 "이름표"
# 자료형  = 그 값이 "어떤 종류" 인가
# 종류마다 하는 일이 다르기 때문에 종류를 나눔
print(10 + 5)  # 15 -> 숫자끼리 더하면 "계산"
print("10" + "5")  # 105 -> 문자열끼리 더하면 "이어 붙이기"
print("10" + 5)  # TypeError -> 종류가 다르면 더할 수 없음
# 겉보기에는 같은 10이지만 결과가 다름 -> 자료형에 주의!


# --------------------------------------------------------
# 2. 자료형 확인
# --------------------------------------------------------
# type() <- 타입 안에 넣으면 어떤 자료형인지 확인 가능
print(type(10))  # int 정수
print(type(3.14))  # float 실수
print(type("안녕"))  # str 문자형
print(type(True))  # bool 불리언
print(type(None))  # None

# 특정 자료형이 맞는지 확인할 때는 isinstance()
print(isinstance(10, int))  # True
print(isinstance(10, str))  # False


# --------------------------------------------------------
# 3. int - 정수
# --------------------------------------------------------
age = 25  # 양수
temperature = -10  # 음수
zero = 0  # 0

# 자릿수 제한이 없어서 아주 큰 수도 그대로 계산된다
big = 123456789123456789 * 999999
print(big)  # 계산이 가능

# 읽기 어려운 큰 수는 언더스코어로 구분이 가능하고 실행에 영향 없음
population = 51_000_000  # 5100만과 동일

# 정수 연산
print(7 + 3)  # 10 더하기
print(7 - 3)  # 4 빼기
print(7 / 3)  # 2.3333333(실수) 나누기
print(7 // 3)  # 2 나눗셈의 몫(소수점 이하 버림)
print(7 % 3)  # 나눗셈의 나머지(짝홀 판별에 주로 사용)
print(7**3)  # 거듭제곱

# 짝수 판별 예시
number = 10
print(number % 2 == 0)  # True -> 2로 나눈 나머지가 0이면 짝수


# --------------------------------------------------------
# 4. float - 실수
# --------------------------------------------------------
height = 175.5
pi = 3.14159
minus = -0.5
exp = 1.5e3  # 지수 표기 1.5 * 10^3
print(exp)  # 1500.0

# float의 함정 : 소수 계산에 오차가 생김
print(0.1 + 0.2)  # 0.3000002
print(0.1 + 0.2 == 0.3)  # False <- == 비교하면 안됨

# 컴퓨터는 숫자를 2진수로 저장하기 때문에 소수를 2진수로 정확히 표현할 수 없음
# 10진수로 1/3을 0.33333333으로 밖에 쓸 수 없는 것과 동일한 원리

# 해결법 1 : 반올림해서 비교
print(round(0.1 + 0.2, 2) == 0.3)  # True -> round(값, 소수점 자리)

# 해결법 2 : 돈 계산처럼 정확하면 decimal 모듈을 사용
from decimal import Decimal

print(Decimal("0.1") + Decimal("0.2"))  # 0.3으로 정확하게 출력

# int와 float을 섞으면?
print(3 + 0.5)  # 3.5 -> 더 정밀한 float으로 맞춰서 출력
print(type(3 + 0.5))  # flaot
print(type(10 / 2))  # 5.0 나눗셈은 정확히 나누어 떨어지더라고 float으로 출력


# --------------------------------------------------------
# 5. str - 문자열
# --------------------------------------------------------
# 따옴표로 감싸면 전부 문자열(작은 따옴표, 큰 따옴표 차이 없음)
name = "철수"
city = "서울"
number_string = "123"  # 따옴표로 감쌌으므로 숫자가 아니라 문자열
# number_string + 1 -> 문자열과 숫자를 더하는 것은 불가능

# 따옴표를 골라서 쓰는 이유
say1 = "그는 '안녕'이라고 말했다."  # 큰 따옴표 안에 작은 따옴표 표기 가능
say2 = "It's a book"  # 같은 따옴표를 쓰고 싶다면 '\'로 탈출

# 여러줄로 문자열 작성
long_text = """ 첫 번째 줄
두 번째 줄
세 번째 줄 """  # 따옴표 3개로 감싸면 줄바꿈이 그대로 저장됨
print(long_text)

# 자주 쓰는 이스케이프 문자
print("줄바꿈\n다음줄")  # \n -> 줄바꿈
print("이름\t나이")  # \t -> 탭(간격)
print("역슬래시 \\ 출력")  # \\ -> \
print(r"C:\new\folder")  # 앞에 r을 붙이면 \가 그대로 출력(폴더 등 경로)


# 문자열 연산
print("파이" + "썬")  # 이어 붙이기
print("하하" * 3)  # 문자열 반복
print(len("파이썬"))  # 3 문자열 길이 세기

# 문자열 연산
word = "PYTHON"
# P Y T H O N
# 0 1 2 3 4 5 <- 인덱스 번호는 0부터 시작
# -5부터 마지막글자인 N은 -1(뒤에서 부터 셀 때에는 음수)
print(word[0])  # P
print(word[-1])  # N

# 잘라내기(슬라이싱)
# word[시작 : 끝] 끝 번호는 포함되지 않음에 주의!
print(word[0:3])  # P Y T 인덱스 넘버 0, 1, 2만 출력
print(word[2:])  # T H O N 인덱스 넘버 2부터 끝까지
print(word[:3])  # P Y T 처음부터 인덱스 넘버 2까지(끝 번호 포함되지 않음)

# 자주 쓰는 문자열 기능
text = "      Hello Python  "
print(text.strip())  # "Hello Python" 앞뒤 공백을 제거
print(text.upper())  # "HELLO PYTHON" 모든 문자가 대문자로 출력
print(text.lower())  # "hello python" 모든 문자가 소문자로 출력
print(text.replace("o", "0"))  # o를 0으로 바꿈
print("사과,배,감".split(","))  # ['사과', '배', '감] 구분자로 나누어 출력

# 문자열은 한 번 만들면 수정 불가
# word[0] = "J" # TypeError
word = "JYTHON"  # 아예 새로 대입하는 것 가능


