# --------------------------------------------------------
# 1. 형 변환이 필요한 이유
# --------------------------------------------------------
# 파이썬은 종류가 다른 값끼리는 계산을 거부
age = "20"
# print(age + 1) # TypeError

# 에러 메세지 해석
# "str" + "int"는 계산이 불가 -> 둘 중 하나의 타입을 바꿔야 함
print(int(age) + 1)  # 21 -> 문자열을 정수형으로 바꾼 후 계산

age = 20
print(str(age))
print(float(age))
print(bool(age))  # True


# --------------------------------------------------------
# 2. 형 변환(2가지)
# --------------------------------------------------------

# (1) 자동 형 변환 : 파이썬이 알아서 맞춰주는 것
result = 3 + 0.5  # int + float
print(result)  # 3.5
print(type(result))  # float 더 정밀한 쪽으로 자동 변환
print(True + 1)  # 2 bool은 숫자로 자동 변환
print(10 / 2)  # 5.0 나눗셈은 항상 float

# (2) 수동 형 변환 : 내가 직접 바꾸는 것
print(int("10"))
print(str(10))
print(float("3.14"))


# --------------------------------------------------------
# 3. int() - 정수로 바꾸기
# --------------------------------------------------------

# 문자열을 정수로 변환
print(int("100"))  # 100
print(int("-50"))  # -50
print(int("   42   "))  # 42 앞뒤 공백은 무시하고 출력

# 실수를 정수로 변환
print(int(3.9))  # 3 반올림이 아닌 버림에 주의!
print(int(3.1))  # 3
print(int(-3.9))  # -3 음수는 0쪽으로 버림

# 반올림이 필요한 경우 round() 사용
print(round(3.9))  # 4
print(round(3.1))  # 3

# bool을 정수로 변환
print(int(True))  # 1
print(int(False))  # 0

# int()로 변환할 수 없는 경우
# print(int("3.14")) # ValueError : 소수점이 든 문자열은 바로 변환할 수 없음
# print(int(float("3.14"))) # 3 float을 거쳐 두 번 변환

# print(int("열")) 한글 숫자는 변환 불가
# print(int("abc")) 숫자가 아닌 문자열은 불가
# print(int("")) 빈 문자열도 불가
# print(int(None)) 불가

# 2진수, 16진수 문자열 변환
print(int("1010"), 2)  # 10 -> 2진수로 해석
print(int("ff"), 16)  # 255 -> 16진수로 해석


# --------------------------------------------------------
# 4. float() - 실수로 바꾸기
# --------------------------------------------------------
print(float("3.14"))  # 3.14
print(float("10"))  # 10.0
print(float(10))  # 10.0
print(float(True))  # 1.0

# 실패하는 경우는 int() 실패의 경우와 같다
print(float("삼점일사"))

# 실수를 정수로 되돌릴 때 소수점이 사라지는 것에 주의!
price = 3.99
print(int(price))  # 3


# --------------------------------------------------------
# 5. str() - 문자열로 바꾸기
# --------------------------------------------------------
# str()은 거의 실패하지 않음(무엇이든 문자열로 변환 가능)
print(str(100))  # "100"
print(str(3.14))  # "3.14"
print(str(True))  # "True"
print(str(None))  # "None"
print(str([1, 2, 3]))  # "[1, 2, 3]"

# str()을 사용하는 경우 : 숫자와 문자를 이어 붙일 때
score = 95
# print("점수 :" + score) 불가능
print("점수 :" + str(score))

# f-string을 사용하면 str()이 필요 없음(더 간편)
print(f"점수 : {score}")  # 점수 : 95

# 문자열이 된 숫자는 더 이상 계산이 불가능
num = str(10)
print(num * 3)  # 101010


# --------------------------------------------------------
# 6. bool() - 참/거짓으로 바꾸기
# --------------------------------------------------------
# 비어 있거나 0이면 False, 나머지는 전부 True
# 문자열은 내용과 상관 없이 '빈 문자열이 아님'이 기준임에 주의!
print(bool(0))  # False
print(bool("0"))  # True
print(bool(""))  # False
print(bool(-5))  # True
print(bool([]))  # False
print(bool(0))  # False
print(bool([] == ""))  # False -> 서로 다른 자료형(리스트와 문자열은 같지 않음)
