# 만들기와 꺼내기
# --------------------------------------------------------

person = {"name": "김철수", "age": "25"}
#           키     값       키     값

print(type(person))  # dict
empty = {}  # 빈 딕셔너리

print(person["name"])  # 김철수
# print(person["phone"])      # KeyError -> 존재하지 않는 키

# get()을 쓰면 없는 키를 찾아도 에러가 나지 않는다!
print(person.get("phone"))  # None -> 존재 여부 확인
print(person.get("phone"), "있는 지 확인")
# 사용자 입력처럼 무엇이 들어올 지 모를 때 [] 대신 get() 사용 권장(안전)

print("name" in person)  # True -> 값을 찾는 것이 아니라 키 존재를 검사
