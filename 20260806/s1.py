# --------------------------------------------------------
# 추가 / 수정 / 삭제
# --------------------------------------------------------

person = {"name": "김철수", "age": "25"}
person["city"] = "서울"  # 딕셔너리에 없는 키 -> 추가
person["age"] = 26  # 이미 딕셔너리에 있는 키 -> 수정

# 추가와 수정의 문법이 동일!
# 오타가 있을 경우 새로운 키가 생성되므로 주의!

person["agee"] = 30  # 에러가 나지 않고 agee라는 키가 생성

del person["agee"]  # agee키 삭제

removed = person.pop("city")  # 해당 키를 삭제하면서 값을 반환
print(removed)  # 서울 -> person 딕셔너리의 city키 삭제, 값인 서울 출력


# --------------------------------------------------------
# 키:값 한꺼번에 받기
# --------------------------------------------------------

scores = {"국어": 90, "영어": 85, "수학": 77}
print(list(scores.keys()))  # ["국어", "영어", "수학"]
print(list(scores.values()))  # [90, 85, 77]
print(len(scores))  # 3

# values()를 뽑으면 리스트처럼 계산 가능
s_sum = sum(scores.values())  # 키 값의 합
print(s_sum)
s_avg = sum(scores.values()) / len(scores)  # 키 값의 평균
print(s_avg)
max_num = max(scores.values())  # 가장 큰 값
print(max_num)
sort_num = sorted(scores.values())[1]  # 중간 값
print(sort_num)


