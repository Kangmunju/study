# --------------------------------------------------------
# 잘라내기 - 슬라이싱
# --------------------------------------------------------

numbers = [10, 20, 30, 40, 50]
print(numbers[1:3])  # [20, 30] -> 끝 번호는 포함하지 않음
print(numbers[:3])  # [10, 20, 30] -> 처음부터 끝 번호 전까지
print(numbers[2:])  # [30, 40, 50] -> 두번째부터 끝까지
print(numbers[-2:])   # [40, 50]  -> 뒤에서 2개
print(numbers[::2])   # [10, 30, 50]  -> 2칸씩 건너뛰기

# [::-1]이면 뒤집힌다
print(numbers[::-1])    # [50, 40, 30, 20, 10]
# reverse()와 달리 원본을 건드리지 않고 새 리스트를 생성
# 문자열에서도 사용 가능
# "안녕하세요"[::-1]




