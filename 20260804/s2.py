# --------------------------------------------------------
# 4. if-elif-else - 갈림길이 여러개
# --------------------------------------------------------

score = 85
if score >= 90:  # 참인지 확인 -> False
    print("A")
elif score >= 80:  # 참인지 확인 -> True -> 멈춤
    print("B")  # 출력 후 종료
elif score >= 70:
    print("C")
else:
    print("F")

# 핵심
# 위에서부터 검사하고 참인 경우가 있으면 실행 후 나머지는 건너뜀
# score = 85 일때
# 1) score >= 90 -> False 다음으로
# 2) score >= 80 -> True 실행 후 조건문을 빠져나감
# 3) 이하 검사하지 않음

# 순서가 매우 중요!
score = 95
if score >= 70:  # 가장 느슨한 조건을 위에 둔 경우
    print("C")  # 95점 인데도 C 등급으로 출력
elif score >= 90:
    print("A")  # 여기까지 오지 못함

# 규칙 : 좁은(까다로운) 조건부터 위에 작성

# elif는 여러개 작성 가능, else는 생략이 가능
weather = "비"
if weather == "맑음":
    print("산책하기 좋음")
elif weather == "비":
    print("우산")
else:
    print("X")

# else가 없으면 아무 조건에도 맞지 않을 때 아무것도 하지 않음


# --------------------------------------------------------
# 5. if를 여러개 쓰는 것 vs elif를 사용
# --------------------------------------------------------

# 겉보기에는 비슷하지만 동작이 완전히 다름
number = 15

# elif : 하나만 실행
if number > 10:  # 이 부분만 실행
    print("10보다 큼")
elif number > 5:  # 실행되지 않음
    print("5보다 큼")

# if를 여러개 : 각각 따로 검사하므로 여러개 실행될 수 있음
if number > 10:  # 실행
    print("10보다 큼")
if number > 5:  # 실행
    print("5보다 큼")

# 등급 판정처럼 '하나만 골라야'하면 elif
# '조건들이 서로 독립적'이면 if 여러개로 각각 검사


