has_ticket = True

if age >= 20 and has_ticket:  # 둘 다 참인 경우
    print("입장 가능")

if age < 8 or age >= 80:  # 둘 중 하나가 참인 경우
    print("할인 대상")

if not has_ticket:
    print("티켓을 구매하세요")

# 범위는 한 줄로 작성 가능
score = 84
if 80 <= score < 90:
    print("B")

# 가장 많이 하는 실수 : 조건을 반쪽만 씀
day = "토"

# if day == "토" or "일"          # 항상 True
if day == "토" or day == "일":
    print("주말")

# in을 사용하면 더욱 깔끔
