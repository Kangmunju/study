# 8. 중첩 조건문(조건문 안에 조건문)
# --------------------------------------------------------

age = 25
has_ticket = False

if age >= 20:
    print("나이 확인 완료")
    if has_ticket:
        print("입장하세요.")
    else:
        print("티켓을 구매하세요.")
else:
    print("성인만 입장 가능!")

# 코드가 너무 길어지면 가독성이 떨어짐
# 위의 코드는 and를 사용하여 합칠 수 있다
if age >= 20 and has_ticket:
    print("입장하세요")  # 그러나 모든 조건을 다 담을 수 없음

# 기준 : 중첩 2단계 까지는 허용, 3단계를 넘어가면 구조를 다시 생각할 것!


