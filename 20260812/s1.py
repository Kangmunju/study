# else 와 finally
# --------------------------------------------------------

# try : 위험한 코드
# except : 에러가 발생한 경우에만
# else : 에러가 나지 않았을 경우에만
# finally : 에러 발생의 유무와 관계 없이 무조건

# 실행 순서 정리
# 에러가 발생하지 않은 경우 : try 전체 -> else -> finally
# 에러가 발생한 경우 : try 일부 -> except -> finally
# 어느 경우이든 finally는 항상 실행!

def check(value):
    print(f"\n [{value}] 처리 시작")
    try:
        num = int(value)
    except ValueError:
        print("except 실행 : 변환 실패")
    else:
        print(f"else 실행 : 변환 성공 {num}")
    finally:
        print("finally 실행 : 이 줄은 항상 실행")
check("100")      # 성공하는 경우
check("백")     # 실패하는 경우

# else를 사용하는 경우
# try 안에는 에러가 날 수 있는 최소한의 코드만 두고
# 성공했을 때 실행하려는 동작은 else 부분에 작성하면 코드가 명확

# finally를 사용하는 경우
# 보통 뒷정리를 할 때 사용 -> 파일 닫기
# 파일을 열었다면 에러 발생의 유무와 무관하게 파일을 닫아야 함
# 후에 배울 with문이 자동으로 해결하기는 한다







