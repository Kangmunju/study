# 리스트 또한 return으로 다루는 것이 안전
# --------------------------------------------------------

og = [3, 1, 2]

def sort_bad(data):
    data.sort()
    return data
def sort_good(data):
    new_data = sorted(data)
    return new_data
result = sort_good(og)
print("sort_good 후 원본 : ", og, "결과 : ", result)
result = sort_bad(og)
print("sort_bad 후 원본 : ", og, "결과 : ", result)

# 함수가 몰래 원본을 변경하면 나중에 혼란스러운 결과 초래
# 특히 여러 사람이 사용하는 코드에서는 반드시 주의할 것!







