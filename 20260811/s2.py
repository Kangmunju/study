# 전역 변수 (global) : 함수 '밖'에서 만든 변수 -> 프로그램 전체에서 살아있음!
# 지역 변수 (local) : 함수 '안'에서 만든 변수 -> 함수가 끝나면 사라짐!

# 전역 변수 - 거실에 둔 물건, 가족 모두가 볼 수 있음
# 함수가 끝나는 것 - 내 방에 둔 물건, 방 밖에서는 볼 수 없음
# 함수가 끝나는 것 - 방을 나오면서 그 안에 있던 물건이 사라지는 것

count = 10      # 전역 변수(함수 밖)
def test():
    temp = 5      # 지역 변수(함수 안)
    print("함수 안에서 count를 읽기 : ", count)     # 전역 변수 읽기 가능
    print("함수 안에서 temp를 읽기 : ", temp)     # 지역 변수 읽기 가능
# print(temp) <- 불가능
test()

print("함수 밖에서 count를 읽기 : ", count)
# print("함수 밖에서 temp를 읽기 : ", temp )      <- Error






# --------------------------------------------------------
# 읽기는 가능하지만 쓰기가 불가능 - 가장 헷갈리는 부분!
# --------------------------------------------------------

num = 10
def change():
    num = 99
    print("함수 안에서 본 num : ", num)
print("함수 실행 전의 num : ", num)     # 10
change()                              # 99
print("함수 실행 후의 num : ", num)     # 10

# 값이 바뀌지 않은 이유
# 파이썬은 함수 안에서 '변수 = 값'을 본 순간
# 이 함수에서 쓸 새로운 지역 변수를 생성한 것으로 이해
# 즉 함수 안의 num과 함수 밖의 num은 이름만 같을 뿐 완전히 다른 변수!
# 함수 안의 num은 함수가 끝나면서 사라졌고, 함수 밖의 num은 처음부터 손대지 않았음

num = 10
def change(num):
    num += 1
    print("함수 안에서 본 num : ", num)
print("함수 실행 전의 num : ", num)     # 10
change(num)                              # 11
print("함수 실행 후의 num : ", num)     # 10








