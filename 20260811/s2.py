# scores.append(100) <- 내용을 수정 = 원본을 직접 건드리는 것
# append, remove, sort 등은 원본을 변경
# 딕셔너리의 dict["key"] = 값 또한 원본을 변경

names = ["철수", "영희"]
def replace_all():
    names = ["민수"]      # 지역변수를 새로 만든 것
    names.append("민수")      # 새로 만든 지역변수인 names리스트에 "민수" 추가
print(names)      # ['철수', '영희']    <- 바뀌지 않고 원래의 names 그대로 출력

# 대입(=) : 지역변수가 새로 생성, 밖은 바뀌지 않는다
# 내용 수정 : 원본이 변경(append, 인덱스 접근, 딕셔너리의 키 등)
# 이러한 차이 때문에 혼란에 빠지지 않도록 주의!







