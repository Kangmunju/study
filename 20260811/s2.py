# --------------------------------------------------------
# global 키워드
# --------------------------------------------------------

total = 0
def add_global(x):
    global total      # 밖에 있는 전역변수 total을 사용하겠다고 선언
    total += x

# global을 쓰면 함수 안에서 전역변수 변경 가능






# --------------------------------------------------------
# global을 사용하지 말아야 하는 이유
# --------------------------------------------------------

money = 10000
def buy_coffee():
    global money
    money -= 4500
def buy_lunch():
    global money
    money -= 8000
def get_paid():
    global money
    money += 5000

buy_coffee()
buy_lunch()
get_paid()
print("남은 돈 : ", money)
# 문제점 : money가 어디서 바뀌었는지 추적이 불가
# 함수가 많은 경우 어느 부분에서 문제였는 지 다 열어봐야 함
# 함수만 봐서는 무엇을 하는 지 알 수 없음
# buy_coffee()라고만 써있다면 money를 건드리는 것인지 파악이 불가
# 함수를 자판기에 비유한 이유 : global은 자판기가 몰래 벽을 뚫고 옆 방 물건을 바꾸는 것과 같다!







