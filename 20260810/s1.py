# 조건이 참(True)인 동안 같은 코드를 계속 반복하는 문법

# while문의 3요소
# 1) 초기화 : 반복에 쓸 변수를 미리 만들어 둔다(i = 1).
# 2) 조건식 : 언제까지 반복할지 정한다.
# 3) 변화식 : 변수를 바꿔서 언젠가 조건을 거짓으로 만든다.
# -> 3번을 작성하지 않으면 '무한루프' 상태에 빠지므로 주의! Ctrl + c 눌러서 빠져 나오기






# --------------------------------------------------------
# 1부터 10까지 더하기
# --------------------------------------------------------

# for문으로 작성
# x = 0
# for i in range(0, 11):
#     x += i
# print(x)

# while문으로 작성
total = 0
n = 1
while n <= 10:
    total += n
    n += 1      # n을 1씩 더함 -> n = 10일때까지(11이 되면 멈춤)
print(total)    # 55

# i = 1     # 1) 초기화
# while i <= 5:   # 2) 조건식(i가 5 이하일때까지)
#     print(i)
#     i += 1      # 3) 변화식




# --------------------------------------------------------
# 거꾸로 세기
# --------------------------------------------------------

count = 5
while count > 0:      # count >= 1 과 동일
    print(count)
    count -= 1




# --------------------------------------------------------
# break - 반복문 즉시 끝내기
# --------------------------------------------------------

num = 1
while num <= 100:
    if num > 5:
        break     # num이 5 초과가 되면 while문 종료(탈출)
    print(num)      # 5
    num += 1
print(num, "확인")      # 6 확인





# --------------------------------------------------------
# continue - 이번 회차만 건너뛰기
# --------------------------------------------------------

k = 0
while k < 10:
    k += 1      # continue 앞에 변화식을 두는 것이 안전!
    if k % 2 == 0:      # k가 짝수라면
        continue        # 아래 print()를 건너뛰고 조건식으로 이동
    print(k)

# 만약 k += 1 을 print()아래에 둔 경우라면
# 짝수에서 continue -> 계속 건너뛰게 되면서 k값이 1씩 늘어나지 않아 '무한루프'






# --------------------------------------------------------
# while True + break (가장 실무에서 많이 쓰는 형태)
# --------------------------------------------------------

password = "1234"
tries = 0
while True:
    tries += 1
    pss = input("비밀번호 입력 : ")
    if pss == password:
        print(f"{tries}번째 시도 : 성공!")
        break
    else:
        print(f"{tries}번째 시도 : 실패!")





# --------------------------------------------------------
# while - else (파이썬에만 존재하는 문법)
# --------------------------------------------------------

# break 없이 조건이 거짓이 되어 정상 종료된 경우에만 else 실행

x = 1
while x <= 3:
    print("반복 중 : ", x)
    x += 1
else:
    print("break 없이 정상 종료 -> else 실행!")





# --------------------------------------------------------
# 누적 & 조건 조합 - 2의 거듭제곱
# --------------------------------------------------------

# 처음 1000을 넘는 2의 거듭제곱 구하기
value = 1
power = 0
while value <= 1000:
    value *= 2
    power += 1
print(f"2^{power} = {value}")       #2^10 = 1024





# --------------------------------------------------------
# for문과의 차이점
# --------------------------------------------------------

# for: 반복 횟수를 '이미 알고 있는 경우' -> 리스트, range()등
# while : 반복 횟수를 '모르는 경우' -> 조건이 만족될 때까지

for i in range(1, 4):
    print("for : ", i)

i = 1
while i < 4:
    print("for : ", i)      # 3
    i += 1
print(i)      # 4





