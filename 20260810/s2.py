# --------------------------------------------------------
# 수학의 함수 vs 파이썬의 함수
# --------------------------------------------------------

# [수학]                               [파이썬]
# f(x) = 2x + 1                       def f(x):
#                                         return 2*x + 1
# 수학에서 x에 3을 대입                 파이썬에서 f(3)을 호출

def f(x):
    return 2 * x + 1
print(f(4))     # 9
print(f(10))      #21

# 주의 : 파이썬에서 곱셈 기호(*)는 생략할 수 없다!
# 수학에서의 2x -> 파이썬에서 2 * x
# 수학에서의 x^2 -> 파이썬에서 x**2(x^2와는 다른 뜻임에 주의!)





# --------------------------------------------------------
# return과 print는 다른 것
# --------------------------------------------------------

# return : 계산 결과를 '값으로 돌려줌' -> 다시 계산에 사용 가능
# print : 화면에 '보여주기만 함' -> 값이 남지 않음

def good(x):
    return 3 * x

def bad(x):
    print(3 * x)

a = good(5)
b = bad(5)

print(a, "a가 나오나요?")     # 15 a가 나요나요? -> return이 있으므로 돌려준 값이 있음!
print(b, "b가 나오나요?")     # None b가 나오나요? -> return이 없으므로 돌려준 값이 없음!

# 수학으로 비유하면
# return이 있는 함수는 진짜 함수 -> f(2)나 f(3) 등을 계산 가능
# print만 있는 함수는 칠판에 답만 작성한 것과 같으므로 그 함수를 다시 사용하는 것 불가능






