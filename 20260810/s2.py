# --------------------------------------------------------
# x절편 구하기 (y = 0이 되는 x)
# --------------------------------------------------------

# ax + b = 0 -> -b/a

def x_in(a, b):
    # y = ax + b의 x절편
    if a == 0:
        # 기울기가 0이면 x절편이 없음
        return None
    return -b / a
print("y = 2x + 1의 x절편 : ", x_in(2, 1))
print("y = 3의 x절편 : ", x_in(0, 3))     # None








