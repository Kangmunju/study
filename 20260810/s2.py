# --------------------------------------------------------
# y = ax + b
# --------------------------------------------------------

# a, b를 인자로 받으면 '모든 일차함수'를 하나의 함수로 표현 가능!

def linear(a, b, x):
    # y = ax + b의 함수값
    # a : 기울기      b : y절편
    return a*x + b
print("y = 2x+1에서 x=4인 경우 : ", linear(2, 1, 4))
print("y = -3x+5에서 x=2인 경우 : ", linear(-3, 5, 2))







# --------------------------------------------------------
# 기울기와 y절편 구하기
# --------------------------------------------------------

# 두 점 (x1, y1) (x2, y2)를 지나는 직선의 기울기
#
#
#         y의 증가량             y2 - y1
# a = ------------------- = ----------------
#         x의 증가량             x2 - x1

def ss(x1, y1, x2, y2):
    # 두 점을 지나는 직선의 기울기
    return (y2 - y1) / (x2 - x1)
print(ss(1,2,3,4))
def line_eq(x1, y1, x2, y2):
    #두 점을 지나는 직선의 식을 구해서 기울기와 y절편 리턴
    a = ss(x1, y1, x2, y2)
    b = y1 - a * x1
    return a, b
# 두 점 (1, 3) (4, 9)를 지나는 직선의 기울기
print(ss(1, 3, 4, 9))
# 그 기울기의 y절편
print(line_eq(1, 3, 4, 9))    #(기울기, y절편)

